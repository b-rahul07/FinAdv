"""
Orchestrator Pipeline — Multi-Agent Sequential Coordinator
=============================================================
This module acts as the "conductor" or "brain" of the AI Financial Advisor.
It connects and executes 4 specialized agents in a strictly controlled sequence:

    Stage 1: Preference Agent      -> Understands user's risk tolerance, financial goals & budget
    Stage 2: Retrieval Agent (RAG) -> Finds verified regulatory & investment knowledge chunks
    Stage 3: Sentiment Agent       -> Analyzes current market sentiment via FinBERT
    Stage 4: Recommend & Audit     -> Synthesizes personalized advice, validates rules & audits provenance

This modular architecture ensures advice is not just generated by an LLM in isolation,
but is actively grounded in factual evidence, current market news, and regulatory rules.
"""

import time
import logging
from dataclasses import dataclass, field
from preference.profile import UserProfile
from preference.agent import elicit_preferences, confirm_profile
from retrieval.agent import RetrievedChunk, retrieve
from sentiment.agent import SentimentSummary, SentimentResult, analyze_sentiment
from recommend_audit.agent import Recommendation, generate_recommendation
import config

# Setup standard logger for pipeline events
logger = logging.getLogger(__name__)


@dataclass
class PipelineResult:
    """
    Data container that bundles the complete output of a single advisory run.
    Contains:
      - profile: The user's parsed risk and financial profile
      - chunks: The text excerpts retrieved from official investment documents
      - sentiment: The market news sentiment score (FinBERT analysis)
      - recommendation: The final advice, recommended portfolio, and audit provenance
      - pipeline_metadata: Execution timings and diagnostics
    """
    profile: UserProfile
    chunks: list[RetrievedChunk]
    sentiment: SentimentSummary
    recommendation: Recommendation
    pipeline_metadata: dict = field(default_factory=dict)


def run_pipeline(
    user_query: str,
    user_responses: dict[str, str],
    profile_edits: dict[str, str] | None = None,
    chat_history: list[dict] | None = None,
    model: str | None = None,
) -> PipelineResult:
    """
    Executes the full 4-stage financial advisor pipeline end-to-end.

    Parameters:
      user_query: The specific question or request entered by the user.
      user_responses: Answers provided by the user to the onboarding questionnaire.
      profile_edits: Any manual corrections made by the user to their risk profile.
      chat_history: Previous conversational messages for context awareness.
      model: The Ollama LLM model name to use (defaults to config.OLLAMA_MODEL).

    Returns:
      A PipelineResult object containing all outputs, evidence, and audit logs.
    """
    # Initialize metadata tracking (timings, ablation toggles, and model used)
    metadata: dict = {
        "ablation_confirmation": config.ENABLE_PREFERENCE_CONFIRMATION,
        "ablation_audit": config.ENABLE_AUDIT_EVIDENCE,
        "model": model or config.OLLAMA_MODEL,
        "timings": {},
    }

    t_start = time.time()

    # --------------------------------------------------------------------------
    # STAGE 1: Preference Elicitation Agent
    # Parses the user's questionnaire answers into a structured UserProfile
    # (extracting monthly surplus, risk tolerance, age, investment horizon, etc.)
    # --------------------------------------------------------------------------
    t0 = time.time()
    logger.info("Stage 1: Eliciting preferences...")
    profile = elicit_preferences(user_responses)

    # Optional confirmation step: allows user to inspect or adjust profile parameters
    profile = confirm_profile(profile, edits=profile_edits)
    metadata["timings"]["preference"] = round(time.time() - t0, 3)
    logger.info(
        f"  Profile: risk={profile.risk_tolerance}, "
        f"horizon={profile.investment_horizon}, confirmed={profile.confirmed}"
    )

    # --------------------------------------------------------------------------
    # STAGE 2: Retrieval Agent (RAG - Retrieval-Augmented Generation)
    # Augments the user's query with their personal profile keywords (goal, risk)
    # and performs a hybrid vector + keyword search over official financial docs.
    # --------------------------------------------------------------------------
    t0 = time.time()
    logger.info("Stage 2: Retrieving relevant documents...")

    # Formulate a enriched search query that combines the user query with user context
    retrieval_query = user_query
    if profile.goal_type and profile.goal_type.lower() not in retrieval_query.lower():
        retrieval_query += f" {profile.goal_type}"
    if profile.risk_tolerance and profile.risk_tolerance.lower() not in retrieval_query.lower():
        retrieval_query += f" {profile.risk_tolerance} risk"
    if profile.investment_horizon and "mutual fund" not in retrieval_query.lower():
        retrieval_query += f" {profile.investment_horizon} mutual fund India"

    # Fetch top matching document chunks from the ChromaDB vector database
    chunks = retrieve(query=retrieval_query, top_k=config.TOP_K_CHUNKS)
    metadata["timings"]["retrieval"] = round(time.time() - t0, 3)
    logger.info(f"  Retrieved {len(chunks)} chunks")

    # --------------------------------------------------------------------------
    # STAGE 3: Sentiment Agent (FinBERT)
    # Analyzes recent live market headlines for the detected investment topic
    # to evaluate whether current market sentiment is Positive, Neutral, or Negative.
    # --------------------------------------------------------------------------
    t0 = time.time()
    logger.info("Stage 3: Analyzing market sentiment...")

    # Identify the key financial topic to fetch headlines for
    sentiment_topic = _extract_sentiment_topic(user_query, profile)

    try:
        sentiment = analyze_sentiment(
            topic=sentiment_topic,
            max_headlines=config.MAX_HEADLINES,
        )
    except Exception as e:
        # Fallback gracefully to neutral sentiment if news fetching or FinBERT model fails
        logger.warning(f"  Sentiment analysis failed: {e}. Using neutral fallback.")
        sentiment = SentimentSummary(
            topic=sentiment_topic,
            overall_sentiment="neutral",
            overall_score=0.0,
            num_headlines=0,
            individual_results=[],
        )

    metadata["timings"]["sentiment"] = round(time.time() - t0, 3)
    logger.info(
        f"  Sentiment: {sentiment.overall_sentiment} "
        f"({sentiment.overall_score:.2f}, {sentiment.num_headlines} headlines)"
    )

    # --------------------------------------------------------------------------
    # STAGE 4: Recommendation + Self-Audit Agent
    # Synthesizes personalized advice using the LLM with all context injected,
    # and subjects the advice to deterministic rule checks (suitability audit).
    # --------------------------------------------------------------------------
    t0 = time.time()
    logger.info("Stage 4: Generating recommendation...")
    recommendation = generate_recommendation(
        profile=profile,
        chunks=chunks,
        sentiment=sentiment,
        user_query=user_query,
        chat_history=chat_history,
        model=model,
    )
    metadata["timings"]["recommendation"] = round(time.time() - t0, 3)
    logger.info(
        f"  Instruments: {recommendation.recommended_instruments}"
    )

    # Record overall pipeline performance metrics
    metadata["timings"]["total"] = round(time.time() - t_start, 3)
    metadata["num_chunks"] = len(chunks)
    metadata["num_headlines"] = sentiment.num_headlines
    metadata["num_rules_fired"] = len(recommendation.provenance.rule_ids)

    return PipelineResult(
        profile=profile,
        chunks=chunks,
        sentiment=sentiment,
        recommendation=recommendation,
        pipeline_metadata=metadata,
    )


def run_pipeline_for_eval(
    user_query: str,
    profile: UserProfile,
    model: str | None = None,
    skip_sentiment: bool = False,
    skip_retrieval: bool = False,
    chat_history: list[dict] | None = None,
) -> PipelineResult:
    """
    Executes the pipeline with an already confirmed/existing UserProfile.
    
    This function is used by the FastAPI backend during normal interactive chat
    sessions when the user has already answered onboarding questions, as well as
    by evaluation benchmarks.
    
    Parameters:
      user_query: The user's query or message.
      profile: Pre-existing or confirmed UserProfile object.
      model: LLM model override (optional).
      skip_sentiment: If True, skips news sentiment (useful for ablation tests).
      skip_retrieval: If True, skips document retrieval (useful for baseline tests).
      chat_history: Conversational history to maintain dialogue context.
    """
    metadata: dict = {
        "ablation_confirmation": config.ENABLE_PREFERENCE_CONFIRMATION,
        "ablation_audit": config.ENABLE_AUDIT_EVIDENCE,
        "model": model or config.OLLAMA_MODEL,
        "skip_sentiment": skip_sentiment,
        "skip_retrieval": skip_retrieval,
        "timings": {},
    }

    t_start = time.time()

    # ── Step 1: Retrieval (RAG) ──────────────────────────────────────────
    if skip_retrieval:
        chunks = []
    else:
        t0 = time.time()
        retrieval_query = user_query
        if profile.goal_type:
            retrieval_query += f" {profile.goal_type}"
        chunks = retrieve(query=retrieval_query, top_k=config.TOP_K_CHUNKS)
        metadata["timings"]["retrieval"] = round(time.time() - t0, 3)

    # ── Step 2: Sentiment Analysis ───────────────────────────────────────
    if skip_sentiment:
        sentiment = SentimentSummary(
            topic="",
            overall_sentiment="neutral",
            overall_score=0.0,
            num_headlines=0,
            individual_results=[],
        )
    else:
        t0 = time.time()
        topic = _extract_sentiment_topic(user_query, profile)
        try:
            sentiment = analyze_sentiment(topic=topic, max_headlines=config.MAX_HEADLINES)
        except Exception:
            sentiment = SentimentSummary(
                topic=topic,
                overall_sentiment="neutral",
                overall_score=0.0,
                num_headlines=0,
                individual_results=[],
            )
        metadata["timings"]["sentiment"] = round(time.time() - t0, 3)

    # ── Step 3: Recommendation & Audit ───────────────────────────────────
    t0 = time.time()
    recommendation = generate_recommendation(
        profile=profile,
        chunks=chunks,
        sentiment=sentiment,
        user_query=user_query,
        chat_history=chat_history,
        model=model,
    )
    metadata["timings"]["recommendation"] = round(time.time() - t0, 3)

    # Finalize timing metrics
    metadata["timings"]["total"] = round(time.time() - t_start, 3)
    metadata["num_chunks"] = len(chunks)
    metadata["num_headlines"] = sentiment.num_headlines
    metadata["num_rules_fired"] = len(recommendation.provenance.rule_ids)

    return PipelineResult(
        profile=profile,
        chunks=chunks,
        sentiment=sentiment,
        recommendation=recommendation,
        pipeline_metadata=metadata,
    )


def _extract_sentiment_topic(query: str, profile: UserProfile) -> str:
    """
    Extracts a relevant financial topic from the user query to query news headlines.

    It scans for known asset classes or investment keywords (e.g., mutual funds, gold, SIP).
    If none match, it falls back to the user's declared goal, or default 'Indian stock market'.
    """
    financial_keywords = [
        "mutual fund", "ELSS", "PPF", "NPS", "SIP", "FD", "gold",
        "stock", "equity", "debt", "bond", "nifty", "sensex",
        "real estate", "insurance", "tax", "inflation",
    ]

    query_lower = query.lower()
    for kw in financial_keywords:
        if kw.lower() in query_lower:
            return kw

    # Fall back to goal type if available (e.g., 'retirement', 'tax saving')
    if profile.goal_type:
        return profile.goal_type

    # Default general market topic
    return "Indian stock market"

