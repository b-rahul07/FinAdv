"""
Recommendation Provenance & Audit Trail Verification
======================================================
This module establishes full algorithmic auditability and anti-hallucination tracking.
In critical domains like financial advice, the user and regulatory auditors must know:
  - Which exact document excerpts informed this specific advice?
  - Which market sentiment score was factored in?
  - Which deterministic regulatory rules were applied?
  - Which AI model generated the text?

Anti-Hallucination Citation Verification:
  LLMs are notorious for "citation fabrication" (e.g. inventing a chunk ID like
  `[CHUNK_ID: doc99_chunk01]` that doesn't exist).
  This module programmatically audits the LLM output:
    1. It scans for all `[CHUNK_ID: ...]` tags.
    2. If the cited chunk exists in the retrieved set, the citation is verified and kept.
    3. If the cited chunk was made up by the LLM, it is immediately stripped and flagged.
    4. Claims derived from our deterministic rule engine are tagged with `[RULE_ID: ...]`.
"""

import re
from dataclasses import dataclass, field


@dataclass
class ProvenanceRecord:
    """
    Complete verifiable audit trail attached to every financial recommendation.
    
    Attributes:
      chunk_ids: List of valid document chunk IDs cited in the advice.
      sentiment_score: Quantitative market sentiment (-1.0 to +1.0) applied during generation.
      sentiment_label: Qualitative market sentiment label ('positive', 'negative', 'neutral').
      rule_ids: List of deterministic rules that fired and guided this advice.
      model_used: Identifier of the LLM model that generated the advice (e.g. 'phi4-mini').
      prompt_hash: SHA-256 hash of the exact prompt sent to the LLM (for reproducibility).
      timestamp: ISO 8601 generation timestamp.
      inline_citations: Dictionary mapping specific claim sentences to their source evidence.
      fabricated_chunk_ids: Audit list of any fake chunk IDs the LLM tried to invent.
    """
    chunk_ids: list[str] = field(default_factory=list)
    sentiment_score: float = 0.0
    sentiment_label: str = "neutral"
    rule_ids: list[str] = field(default_factory=list)
    model_used: str = ""
    prompt_hash: str = ""
    timestamp: str = ""
    inline_citations: dict = field(default_factory=dict)
    fabricated_chunk_ids: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        """Serializes provenance metadata into a dictionary for JSON output."""
        return {
            "chunk_ids": self.chunk_ids,
            "sentiment_score": self.sentiment_score,
            "sentiment_label": self.sentiment_label,
            "rule_ids": self.rule_ids,
            "model_used": self.model_used,
            "prompt_hash": self.prompt_hash,
            "timestamp": self.timestamp,
            "inline_citations": self.inline_citations,
            "fabricated_chunk_ids": self.fabricated_chunk_ids,
        }


# ==============================================================================
# Rule-Claim Regex Patterns
# ==============================================================================
# Mapping from rule_id -> keyword signatures used to detect if an advice sentence
# is executing a specific deterministic rule constraint.
_RULE_CLAIM_PATTERNS: dict[str, list[str]] = {
    "rule_80c_limit": [
        "section 80c", "80c deduction", "₹1,50,000", "1,50,000", "1.5 lakh",
        "80c limit",
    ],
    "rule_elss_lockin": [
        "elss lock-in", "elss.*3.year", "3-year lock-in",
        "elss.*lock.in",
    ],
    "rule_ppf_lockin": [
        "ppf lock-in", "ppf.*15.year", "15-year lock-in",
        "ppf.*lock.in", "partial withdrawal after 7",
    ],
    "rule_emi_ratio": [
        "emi-to-income", "emi ratio", "emi burden",
        "debt reduction", "emergency fund before",
        "emi.*exceed", "emi.*high",
    ],
    "rule_bnpl_warning": [
        "bnpl", "buy now pay later", "over-leverag",
        "clear bnpl", "bnpl exposure", "bnpl risk",
    ],
}


def attach_rule_provenance(
    text: str,
    fired_rule_ids: list[str],
) -> str:
    """
    Scans the generated text for sentences that reflect fired financial rules
    and appends an explicit `[RULE_ID: rule_xxx]` tag after the relevant claim.

    Ensures that only rules that ACTUALLY fired for this user's profile get tagged.

    Parameters:
      text: The raw advice text generated by the LLM.
      fired_rule_ids: List of rule IDs that evaluated to True for this user.

    Returns:
      Text with rule provenance tags attached.
    """
    if not fired_rule_ids:
        return text

    for rule_id in fired_rule_ids:
        patterns = _RULE_CLAIM_PATTERNS.get(rule_id, [])
        for pat in patterns:
            # Match complete sentences containing the rule keyword pattern
            regex = re.compile(
                r'([^.!?\n]*' + pat + r'[^.!?\n]*[.!?])',
                re.IGNORECASE,
            )
            for match in regex.finditer(text):
                tag = f" [RULE_ID: {rule_id}]"
                # Prevent duplicate tags on the same claim
                if tag not in text[match.start():match.end() + len(tag) + 5]:
                    text = text[:match.end()] + tag + text[match.end():]
                    break  # Tag once per rule per advice block

    return text


# Regex pattern to identify citations formatted as [CHUNK_ID: ...]
_CHUNK_ID_RE = re.compile(r'\[CHUNK_ID:\s*([^\]]+)\]')


def verify_chunk_citations(
    text: str,
    valid_chunk_ids: set[str],
) -> tuple[str, list[str]]:
    """
    Audits every `[CHUNK_ID: xyz]` citation in the text against the actual retrieved chunks.

    Verification Logic:
      - Valid Citations: If `xyz` is in `valid_chunk_ids`, keep it in the text.
      - Hallucinated Citations: If `xyz` is NOT in `valid_chunk_ids`, strip it from the
        text so the user is not deceived, and add it to `fabricated_ids` for logging.

    Parameters:
      text: The raw generated recommendation text.
      valid_chunk_ids: Set of chunk IDs that were legitimately retrieved from ChromaDB.

    Returns:
      Tuple of (cleaned_text_without_fake_citations, list_of_fabricated_chunk_ids).
    """
    fabricated: list[str] = []

    def _replacer(m: re.Match) -> str:
        cid = m.group(1).strip()
        if cid in valid_chunk_ids:
            return m.group(0)          # Verified citation: keep it
        fabricated.append(cid)         # Hallucinated citation: record and delete
        return ""

    cleaned = _CHUNK_ID_RE.sub(_replacer, text)
    return cleaned, fabricated


def attach_provenance(
    text: str,
    fired_rule_ids: list[str],
    valid_chunk_ids: set[str],
) -> tuple[str, list[str]]:
    """
    Unified entry point for recommendation post-processing:
      1. Verifies and filters all document chunk citations.
      2. Annotates rule-driven financial claims with verifiable rule IDs.

    Parameters:
      text: The recommendation narrative generated by the model.
      fired_rule_ids: Rules triggered by the user's risk profile.
      valid_chunk_ids: Legitimate document chunk IDs from RAG retrieval.

    Returns:
      Tuple of (fully_annotated_text, list_of_any_fabricated_chunk_ids).
    """
    # Step 1: Strip any hallucinated document chunk citations
    text, fabricated = verify_chunk_citations(text, valid_chunk_ids)

    # Step 2: Inject verified regulatory rule tags
    text = attach_rule_provenance(text, fired_rule_ids)

    return text, fabricated

