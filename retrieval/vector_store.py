"""
Vector Store Interface (ChromaDB Wrapper)
===========================================
This module provides an abstraction over ChromaDB, our local vector database.
It is responsible for:
  1. Initializing and managing the persistent ChromaDB collection on disk.
  2. Converting text chunks into 384-dimensional dense vectors using SentenceTransformers.
  3. Storing and indexing document embeddings with metadata.
  4. Executing fast approximate nearest neighbor (ANN) vector similarity search.
"""

import chromadb
from chromadb.utils import embedding_functions
from retrieval.chunker import Chunk

# Singleton handles for ChromaDB client and collection
_client = None
_collection = None


def initialize_store(
    persist_dir: str = "./data/chroma_db",
    embedding_model: str = "sentence-transformers/all-MiniLM-L6-v2"
) -> None:
    """
    Connects to the persistent ChromaDB database on disk and sets up the embedding model.

    Parameters:
      persist_dir: Folder path where SQLite index and vectors are saved.
      embedding_model: Hugging Face model identifier for SentenceTransformers.
    """
    global _client, _collection
    # Create or open local persistent Chroma client
    _client = chromadb.PersistentClient(path=persist_dir)
    
    # Load SentenceTransformer embedding function (converts strings -> float vectors)
    ef = embedding_functions.SentenceTransformerEmbeddingFunction(model_name=embedding_model)
    
    # Connect to the 'finadvisor_docs' collection (or create if first time running)
    _collection = _client.get_or_create_collection(
        name="finadvisor_docs",
        embedding_function=ef
    )


def add_chunks(chunks: list[Chunk]) -> None:
    """
    Embeds and upserts a list of document Chunk objects into the Chroma collection.

    Parameters:
      chunks: List of Chunk objects generated by the document chunker.
    """
    if _collection is None:
        raise RuntimeError("Vector store not initialized. Call initialize_store() first.")

    if not chunks:
        return

    # Extract IDs, text content, and metadata dictionaries
    ids = [c.chunk_id for c in chunks]
    documents = [c.content for c in chunks]
    metadatas = [c.metadata for c in chunks]

    # Upsert ensures that existing chunks are updated and new ones are inserted
    _collection.upsert(
        ids=ids,
        documents=documents,
        metadatas=metadatas
    )


def search(query: str, top_k: int = 5, filters: dict | None = None) -> list[dict]:
    """
    Performs cosine / L2 vector similarity search to find chunks matching the query.

    Parameters:
      query: The question or search term.
      top_k: Number of most similar chunks to return.
      filters: Optional metadata filtering dictionary (e.g., {"source": "SEBI.pdf"}).

    Returns:
      List of result dictionaries containing chunk_id, content, metadata, and relevance_score.
    """
    if _collection is None:
        raise RuntimeError("Vector store not initialized. Call initialize_store() first.")

    # Query ChromaDB collection with automatic query embedding
    results = _collection.query(
        query_texts=[query],
        n_results=top_k,
        where=filters
    )

    # Format the nested Chroma results into a clean list of dictionaries
    parsed_results = []
    if results['ids'] and len(results['ids'][0]) > 0:
        for i in range(len(results['ids'][0])):
            parsed_results.append({
                "chunk_id": results['ids'][0][i],
                "content": results['documents'][0][i],
                "metadata": results['metadatas'][0][i],
                "relevance_score": results['distances'][0][i] if 'distances' in results and results['distances'] else 0.0
            })

    return parsed_results

