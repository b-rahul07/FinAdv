"""Write supabase/schema.sql from the SQLAlchemy models, with row-level security switched on.

The API connects as the database owner (bypasses RLS). Enabling RLS with no policies means the
public Data API (anon/authenticated keys) can read or write nothing: a second layer behind the API.

Run: python scripts/gen_postgres_schema.py
"""

from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

import finadvisor.db.models  # noqa: F401  (registers tables)
from finadvisor.db.base import Base

OUT = Path(__file__).resolve().parent.parent / "supabase" / "schema.sql"


def main() -> None:
    dialect = postgresql.dialect()
    parts = ["-- Generated by scripts/gen_postgres_schema.py from finadvisor/db/models.py. Do not edit by hand.",
             "-- Apply in the Supabase SQL editor (or psql) on an empty database.", ""]
    for t in Base.metadata.sorted_tables:
        parts.append(str(CreateTable(t).compile(dialect=dialect)).strip() + ";")
        for ix in t.indexes:
            parts.append(str(CreateIndex(ix).compile(dialect=dialect)).strip() + ";")
        parts.append(f"ALTER TABLE {t.name} ENABLE ROW LEVEL SECURITY;")
        parts.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({len(Base.metadata.sorted_tables)} tables)")


if __name__ == "__main__":
    main()
